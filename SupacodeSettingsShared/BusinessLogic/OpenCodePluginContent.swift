import Foundation

/// Sources for the OpenCode plugins that bridge OpenCode's plugin events to
/// Supacode's OSC 3008 agent-presence protocol.
///
/// OpenCode does NOT consume a Claude-style declarative `hooks` block in its
/// config (`opencode.json`). Its extensibility surface is JS/TS plugins
/// auto-loaded from `~/.config/opencode/plugins/`. So instead of writing a
/// settings file, Supacode installs small plugins that run the exact same
/// guarded shell command every other agent's hooks run — keeping the OSC
/// template, surface guard, tty resolve, and pid-liveness suffix single-sourced
/// in `AgentHookSettingsCommand`.
///
/// The command must run in the process that owns the user's terminal. OpenCode
/// 1.x runs server plugins in that process. OpenCode 2.x runs them in a shared,
/// detached service with no tty and another client's environment, so 2.x gets a
/// TUI plugin instead, which runs inside the terminal's own process.
nonisolated enum OpenCodePluginContent {
  /// Top-level file under `plugins/`: OpenCode 1.x's server plugin. 2.x also
  /// loads it as a server plugin, so it carries a no-op 2.x `setup`. A default
  /// export object needs OpenCode 1.3.4+; older loaders call every export.
  static let serverFileName = "supacode-presence.js"

  /// Directory under `plugins/` holding the OpenCode 2.x TUI entrypoint. 1.x
  /// ignores subdirectories, and the 2.x server skips a directory with no
  /// `server` or `index` entrypoint.
  static let tuiDirectoryName = "supacode-presence"
  static let tuiFileName = "tui.js"

  /// Marker that identifies a Supacode-managed plugin file. The composite
  /// command embeds `AgentHookSettingsCommand.ownershipMarker` verbatim, so the
  /// generated sources always contain it — uninstall keys off this so it never
  /// deletes a user file that merely shares the name.
  static let ownershipMarker = AgentHookSettingsCommand.ownershipMarker

  /// Deterministic plugin sources (no timestamps), so `installState` can detect
  /// a byte-for-byte match vs. an older Supacode version's plugin (`.outdated`).
  static func serverSource() -> String {
    """
    // \(ownershipMarker)
    //
    // Generated by Supacode — do not edit. Bridges OpenCode 1.x plugin events to
    // Supacode's OSC 3008 agent-presence protocol by running the same guarded
    // shell command Supacode installs for every other agent. The command checks
    // SUPACODE_SURFACE_ID first, so it is inert outside a Supacode surface and
    // safe to keep installed anywhere.
    //
    // OpenCode 2.x runs server plugins in a shared service with no terminal, so
    // `setup` is a no-op there and supacode-presence/tui.js reports presence.
    //
    // Presence only: OpenCode's session.idle event carries no assistant text
    // (unlike Claude Code's Stop hook stdin), so the system-notification leg is
    // intentionally omitted rather than fed a fabricated body.
    const server = async ({ $ }) => {
      const emit = (command) => $`sh -c ${command}`.quiet().nothrow()

      // Agent is now present in this surface.
      await emit(\(jsString(command(for: [.sessionStart]))))

      return {
        // Agent (and its surface presence) is going away.
        dispose: async () => {
          await emit(\(jsString(command(for: [.sessionEnd, .idle]))))
        },
        // Tool-level activity shimmer: a tool started / finished.
        "tool.execute.before": async () => {
          await emit(\(jsString(command(for: [.busy]))))
        },
        "tool.execute.after": async () => {
          await emit(\(jsString(command(for: [.idle]))))
        },
        // A permission prompt is the "needs you" state.
        "permission.ask": async () => {
          await emit(\(jsString(command(for: [.awaitingInput]))))
        },
        event: async ({ event }) => {
          if (event.type === "session.idle") {
            await emit(\(jsString(command(for: [.idle]))))
          } else if (event.type === "permission.replied") {
            await emit(\(jsString(command(for: [.busy]))))
          }
        },
      }
    }

    export default { id: "supacode.presence", server, setup() {} }
    """
  }

  /// The TUI receives events for every session the shared service knows about,
  /// including other terminals' sessions, and session tabs are shared between
  /// TUIs in the same directory. So it owns an execution only when its root
  /// session is routed in this TUI or already executing here, adopts a routed
  /// session that is already running, and derives one surface state from every
  /// execution and prompt it owns.
  static func tuiSource() -> String {
    """
    // \(ownershipMarker)
    //
    // Generated by Supacode — do not edit. Bridges OpenCode 2.x TUI events to
    // Supacode's OSC 3008 agent-presence protocol by running the same guarded
    // shell command Supacode installs for every other agent. It runs inside the
    // TUI process, so the command sees this terminal's environment and tty.
    import { spawn } from "node:child_process"

    const run = (command) =>
      new Promise((resolve) => {
        const child = spawn("/bin/sh", ["-c", command], { stdio: "ignore" })
        const timer = setTimeout(() => child.kill("SIGKILL"), \(AgentHookSettingsCommand.timeoutMilliseconds))
        const done = () => {
          clearTimeout(timer)
          resolve()
        }
        child.once("error", done)
        child.once("exit", done)
      })

    const busy = \(jsString(command(for: [.busy])))
    const awaitingInput = \(jsString(command(for: [.awaitingInput])))
    const idle = \(jsString(command(for: [.idle])))
    const error = \(jsString(command(for: [.error])))

    export default {
      id: "supacode.presence.tui",
      async setup({ data, ui }) {
        let queue = Promise.resolve()
        const emit = (command) => (queue = queue.then(() => run(command)))
        const executions = new Map()
        const prompts = new Map()
        let outcome = idle

        const executing = (root) => [...executions.values()].includes(root)
        const routedRoot = () => {
          const route = ui.router.current()
          return route.type === "session" ? data.session.root(route.sessionID) : undefined
        }
        const report = () => {
          if (executions.size === 0) emit(outcome)
          else if (prompts.size > 0) emit(awaitingInput)
          else emit(busy)
        }
        const on = (type, changed) =>
          data.on(type, (event) => {
            try {
              if (changed(event.data)) report()
            } catch {}
          })

        const started = ({ sessionID }) => {
          const root = data.session.root(sessionID)
          if (root !== routedRoot() && !executing(root)) return false
          executions.set(sessionID, root)
          outcome = idle
          return true
        }
        const ended = ({ sessionID }) => {
          const root = executions.get(sessionID)
          if (!executions.delete(sessionID)) return false
          if (!executing(root)) {
            for (const [id, owner] of prompts) if (owner === root) prompts.delete(id)
          }
          return true
        }
        const failed = (event) => {
          if (!ended(event)) return false
          outcome = error
          return true
        }
        const asked = ({ id, sessionID }) => {
          const root = data.session.root(sessionID)
          if (!executing(root)) return false
          prompts.set(id, root)
          return true
        }
        const answered = (id) => prompts.delete(id)
        // The service keeps a turn running after its TUI exits, so a TUI can open
        // a session whose execution, and the prompt blocking it, started before
        // it was there to see them.
        const adoptRouted = () => {
          try {
            const route = ui.router.current()
            if (route.type !== "session") return
            const id = route.sessionID
            let changed = false
            if (!executions.has(id)) {
              if (data.session.status(id) !== "running") return
              changed = started({ sessionID: id })
            }
            const pending = [...(data.session.permission.list(id) ?? []), ...(data.session.form.list(id) ?? [])]
            for (const prompt of pending) {
              if (prompts.has(prompt.id)) continue
              prompts.set(prompt.id, executions.get(id))
              changed = true
            }
            if (changed) report()
          } catch {}
        }

        await emit(\(jsString(command(for: [.sessionStart]))))
        const adoption = setInterval(adoptRouted, 1000)
        const subscriptions = [
          on("session.execution.started", started),
          on("session.execution.succeeded", ended),
          on("session.execution.interrupted", ended),
          on("session.execution.failed", failed),
          on("permission.asked", asked),
          on("form.created", ({ form }) => asked(form)),
          on("permission.replied", ({ requestID }) => answered(requestID)),
          on("form.replied", ({ id }) => answered(id)),
          on("form.cancelled", ({ id }) => answered(id)),
        ]

        return async () => {
          clearInterval(adoption)
          subscriptions.forEach((unsubscribe) => unsubscribe())
          await emit(\(jsString(command(for: [.sessionEnd, .idle]))))
        }
      },
    }
    """
  }

  private static func command(for events: [HookEvent]) -> String {
    AgentHookSettingsCommand.compositeCommand(
      events: events, forwardStdinAsNotification: false, agent: .opencode)
  }

  /// JSON-encoding a `String` yields a valid double-quoted JavaScript string
  /// literal: it escapes `"`, `\`, and control characters, and the composite
  /// command contains no newlines. `$` and backticks are literal inside a
  /// double-quoted JS string, so no extra escaping is needed.
  private static func jsString(_ value: String) -> String {
    guard
      let data = try? JSONEncoder().encode(value),
      let literal = String(data: data, encoding: .utf8)
    else {
      return "\"\""
    }
    return literal
  }
}
